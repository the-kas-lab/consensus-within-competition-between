def ci_pp(lo, hi):
    return f"{signed_pp(lo)} to {signed_pp(hi)}"


def drop_p(lines):
    """Drop the two P columns (last two cells) of a comparison table; keep the dagger on the CI cell."""
    out = []
    for ln in lines:
        m = re.match(r"\\multicolumn\{(\d+)\}(.*)", ln)
        if m:
            out.append(f"\\multicolumn{{{int(m.group(1)) - 2}}}{m.group(2)}")
            continue
        if " \\\\" not in ln:  # rules such as \addlinespace or \midrule
            out.append(ln)
            continue
        body, end = ln.rsplit(" \\\\", 1)
        cells = body.split(" & ")
        dag = flag(True) if "\\dag" in cells[-1] else ""
        cells = cells[:-2]
        cells[-1] += dag
        out.append(" & ".join(cells) + " \\\\" + end)
    return out


def flag(d):
    return "\\textsuperscript{\\dag}" if d else ""


