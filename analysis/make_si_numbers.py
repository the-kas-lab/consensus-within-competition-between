MAIN_SOURCES = {}
for n, (_, src) in MAIN.items():
    MAIN_SOURCES.setdefault(re.sub(r"\s*\(.*$", "", src).strip(), []).append(n)

MACROS = []


def add(name, value, rel, path, note=""):
    """One SI macro. name must start with 'si' (keeps the namespace apart from numbers.tex)."""
    assert name.startswith("si") and re.fullmatch(r"si[A-Za-z]+", name), f"bad SI macro name {name}"
    assert name not in MAIN, f"\\{name} already exists in numbers.tex"
    src = f"{rel} :: {'.'.join(str(p) for p in path)}"
    if src in MAIN_SOURCES:
        raise SystemExit(f"\\{name}: source {src} is already the source of numbers.tex "
                         f"\\{MAIN_SOURCES[src][0]}; use that macro")
    assert name not in {m[0] for m in MACROS}, f"duplicate \\{name}"
    MACROS.append((name, value, src + (f" {note}" if note else "")))


def use(name, value, rel, path, note=""):
    """Macro for a value: the paper's macro if numbers.tex already reads this source leaf with this exact value,
    else a new SI macro. A paper macro on the same leaf with a different value (e.g. other rounding) stops the run."""
    src = f"{rel} :: {'.'.join(str(p) for p in path)}"
    if src in MAIN_SOURCES:
        same = [n for n in MAIN_SOURCES[src] if MAIN[n][0] == value]
        if not same:
            raise SystemExit(f"{name}: {src} is read by numbers.tex {MAIN_SOURCES[src]} with value(s) "
                             f"{[MAIN[n][0] for n in MAIN_SOURCES[src]]}, not {value!r}; decide the format")
        return same[0]
    add(name, value, rel, path, note)
    return name


def tex_int(n):
    """Integer with comma thousands separators."""
    return f"{int(n):,}"


