def use_p(name, v, rel, path):
    """A P value: the paper's macro if it reads this leaf (at 2 or 3 decimals), else an SI macro."""
    src = f"{rel} :: {'.'.join(str(p) for p in path)}"
    for cand in (pval(v), f"{v:.3f}"):
        for n in MAIN_SOURCES.get(src, []):
            if MAIN[n][0] == cand:
                return n
    return use(name, pval(v), rel, path)


