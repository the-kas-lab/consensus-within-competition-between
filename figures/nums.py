"""Shared checks: every number a figure prints or plots must equal the paper's macro.

macro(name) reads numbers.tex and si_numbers.tex (generated by analysis/make_numbers.py and
analysis/make_si_numbers.py from the same JSON leaves). The formatters reproduce make_numbers.py exactly (half-up
rounding on the stored decimal; \\textminus for the minus sign), so `assert_macro` compares like with like.
`t_ci` recomputes a seed-level 95 % t interval, so a figure also checks that the stored interval belongs to the
per-seed values it plots.
"""
from __future__ import annotations

import re
from decimal import ROUND_HALF_UP, Decimal

import numpy as np
from scipy import stats

from figures import paths

NUMBERS = paths.AN / "numbers.tex"
SI_NUMBERS = paths.AN / "si_numbers.tex"   # SI-only values (Supplementary Tables)
_CACHE: dict[str, str] = {}


def macro(name: str) -> str:
    if not _CACHE:
        for line in NUMBERS.read_text().splitlines() + SI_NUMBERS.read_text().splitlines():
            m = re.match(r"\\newcommand\{\\(\w+)\}\{(.*)\} % ", line)
            if m:
                _CACHE[m.group(1)] = m.group(2)
    return _CACHE[name]


def pct(v: float, d: int = 0) -> str:
    q = Decimal("1") if d == 0 else Decimal(1).scaleb(-d)
    return str(Decimal(str(v * 100)).quantize(q, rounding=ROUND_HALF_UP))


def signed_pp(v: float, d: int = 0) -> str:
    s = pct(abs(v), d)
    return ("+" if v > 0 else "\\textminus" if v < 0 else "") + s


def pp_ci(lo: float, hi: float, d: int = 0) -> str:
    return f"{signed_pp(lo, d)} to {signed_pp(hi, d)}"


def pval(v: float) -> str:
    """make_numbers.py's P-value format."""
    return "<0.001" if v < 0.001 else (f"{v:.3f}" if v < 0.01 else f"{v:.2f}")


def assert_macro(name: str, value: str) -> None:
    got = macro(name)
    assert got == value, f"\\{name} = {got!r}, figure has {value!r}"


def t_ci(x, level=0.95):
    x = np.asarray(x, float)
    n = len(x)
    m = x.mean()
    h = stats.t.ppf(0.5 + level / 2, n - 1) * x.std(ddof=1) / np.sqrt(n)
    return m, (m - h, m + h)


def assert_seed_summary(per_seed, est, ci, n=30, tol=6e-5):
    """The stored estimate and t interval are the mean and t interval of the plotted seeds
    (stored values are rounded to 4 dp)."""
    assert len(per_seed) == n, len(per_seed)
    m, (lo, hi) = t_ci(per_seed)
    assert abs(m - est) < tol and abs(lo - ci[0]) < tol and abs(hi - ci[1]) < tol, (m, lo, hi, est, ci)


def tex_to_fig(s: str) -> str:
    """Macro text to figure text: \\textminus -> Unicode minus."""
    return s.replace("\\textminus", "−")
